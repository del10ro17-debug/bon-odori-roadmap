def q(level: str, question: str, choices: list[str], explain: str) -> dict | None:
    if len(choices) != 4 or len(set(choices)) != 4:
        return None
    return {
        "level": level,
        "q": question,
        "choices": choices,
        "answer": 0,
        "explain": explain,
    }


def distract(correct: str, pool: list[str], n: int = 3) -> list[str]:
    opts = [x for x in dict.fromkeys(pool) if x != correct]
    RNG.shuffle(opts)
    filler = ["???A", "???B", "???C", "???D", "???E"]
    i = 0
    while len(opts) < n:
        opts.append(filler[i % len(filler)])
        i += 1
    return opts[:n]


def mc(level: str, question: str, correct: str, wrong_pool: list[str], explain: str) -> dict | None:
    return q(level, question, [correct, *distract(correct, wrong_pool)], explain)


def add(bag: dict[str, dict], item: dict | None) -> None:
    if not item:
        return
    if item["q"] in bag:
        return
    bag[item["q"]] = item


